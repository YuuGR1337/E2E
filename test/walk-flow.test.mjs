test('ariaAssertion keeps backticks, ${ and backslashes literal', () => {
  const snapshot = '- link "Cart `x` ${y} a\\\\b"';
  const code = ariaAssertionCode(snapshot, 'nav');
  assert.equal(code, 'await expect(page.locator("nav")).toMatchAriaSnapshot(`\n  - link "Cart \\`x\\` \\${y} a\\\\\\\\b"\n`);');
  // The template literal evaluates back to the original snapshot.
  const literal = code.slice(code.indexOf('`'), code.lastIndexOf('`') + 1);
  assert.equal(eval(literal).trim(), snapshot);
  assert.match(ariaAssertion('- heading "A"'), /^```ts\nawait expect\(page\.locator\('body'\)\)/);
  assert.match(ariaAssertionCode('- a', undefined, 4), /^ {4}await expect/);
});

test('stepCode writes each walked step as Playwright code', () => {
  const loc = parseLocator("getByRole('button', { name: 'Save' })");
  assert.equal(stepCode({ type: 'click', label: '', locator: loc }), "await page.getByRole('button', { name: 'Save' }).click();");
  assert.equal(stepCode({ type: 'fill', label: '', locator: loc, value: "O'Brien" }), "await page.getByRole('button', { name: 'Save' }).fill('O\\'Brien');");
  assert.equal(stepCode({ type: 'press', label: '', value: 'Enter' }), "await page.keyboard.press('Enter');");
  assert.equal(stepCode({ type: 'select', label: '', locator: loc, value: 'b' }), "await page.getByRole('button', { name: 'Save' }).selectOption('b');");
  assert.equal(stepCode({ type: 'wait', label: '', locator: loc }), "await expect(page.getByRole('button', { name: 'Save' }).first()).toBeVisible();");
  assert.equal(stepCode({ type: 'wait', label: '', ms: 250 }), 'await page.waitForTimeout(250);');
  assert.equal(stepCode({ type: 'goto', label: '', url: 'http://x.test/a' }), "await page.goto('http://x.test/a');");
});

test('endStateAssertions: URL path regex, full snapshot when short, headings when long', () => {
  const short = endStateAssertions({ entryUrl: 'http://x.test/', finalUrl: 'http://x.test/cart.html?id=7', snapshot: '- heading "Cart"' });
  assert.equal(short[0], '    await expect(page).toHaveURL(/\\/cart\\.html(?:[?#]|$)/);');
  assert.match(short[1], /toMatchAriaSnapshot/);
  assert.ok(new RegExp('/cart\\.html(?:[?#]|$)').test('http://x.test/cart.html?id=7'));
  const same = endStateAssertions({ entryUrl: 'http://x.test/', finalUrl: 'http://x.test/' });
  assert.deepEqual(same, []);
  const long = ['- heading "Order \\"42\\""', ...Array.from({ length: 70 }, (_, i) => `- text: row ${i}`)].join('\n');
  const fallback = endStateAssertions({ entryUrl: 'http://x.test/', snapshot: long });
  assert.deepEqual(fallback, ["    await expect(page.getByRole('heading', { name: 'Order \"42\"' })).toBeVisible();"]);
});

test('buildWalkSpec carries the marker, session and end state', () => {
  const spec = buildWalkSpec({
    description: "checkout's flow",
    entryUrl: 'http://x.test/',
    steps: [{ type: 'click', label: '', locator: parseLocator("getByText('Go')") }],
    storageState: 'playwright/.auth/user.json',
    assertions: ['    await expect(page).toHaveURL(/\\/done/);'],
  });
  assert.match(spec, / \* Generated by playwright-e2e-mcp for: "checkout's flow"/);
  assert.match(spec, /test\.describe\('checkout\\'s flow'/);
  assert.match(spec, /test\.use\(\{ storageState: 'playwright\/\.auth\/user\.json' \}\);/);
  assert.match(spec, /await page\.goto\('http:\/\/x\.test\/'\);\n {4}await page\.getByText\('Go'\)\.click\(\);\n\n {4}\/\/ End state/);
});

const ctxFor = (projectRoot, extra = {}) => ({ logger: logger.child({ tool: 'test' }), store: createToolStore(), projectRoot, ...extra });

test('har: replay needs an existing file inside the project; record needs its folder there', async () => {
  const root = realpathSync(mkdtempSync(path.join(os.tmpdir(), 'pw-har-')));
  const outside = realpathSync(mkdtempSync(path.join(os.tmpdir(), 'pw-har-out-')));
  writeFileSync(path.join(root, 'net.har'), '{}');
  mkdirSync(path.join(root, 'fixtures'));
  symlinkSync(outside, path.join(root, 'escape'), 'junction');
  const ctx = ctxFor(root);
  const url = 'http://example.test/';

  const replay = await resolvePageState({ har: { path: 'net.har', url: '**/api/**' } }, root, url, ctx);
  assert.deepEqual(replay.har, { path: path.join(root, 'net.har'), mode: 'replay', url: '**/api/**', notFound: 'abort' });
  assert.equal(describePageState(replay, root), 'HAR replay from `net.har`');

  const record = await resolvePageState({ har: { path: 'fixtures/new.har', mode: 'record' } }, root, url, ctx);
  assert.equal(record.har.mode, 'record');
  assert.equal(describePageState(record, root), 'recording HAR to `fixtures/new.har`');

  await assert.rejects(resolvePageState({ har: { path: 'missing.har' } }, root, url, ctx), /HAR file not found/);
  await assert.rejects(resolvePageState({ har: { path: 'net.json' } }, root, url, ctx), /must end in \.har or \.zip/);
  await assert.rejects(resolvePageState({ har: { path: '../x.har', mode: 'record' } }, root, url, ctx), /outside the project/);
  await assert.rejects(resolvePageState({ har: { path: 'escape/x.har', mode: 'record' } }, root, url, ctx), /outside|symlink/i);
  await assert.rejects(resolvePageState({ har: { path: 'nofolder/x.har', mode: 'record' } }, root, url, ctx), /does not exist/);
  await assert.rejects(resolvePageState({ har: { path: 'net.har' } }, root, url, ctxFor(root, { restricted: true })), /not available on this server/);
});

test('browser: firefox passes through, webkit is refused while private addresses are blocked', async () => {
  const root = realpathSync(mkdtempSync(path.join(os.tmpdir(), 'pw-engine-')));
  const ctx = ctxFor(root);
  const url = 'http://example.test/';
  assert.equal((await resolvePageState({ browser: 'firefox' }, root, url, ctx)).browser, 'firefox');
  assert.equal((await resolvePageState({ browser: 'chromium' }, root, url, ctx)).browser, undefined);
  assert.equal(describePageState({ browser: 'firefox' }, root), 'firefox');
  setBlockPrivateUrls(true);
  try {
    await assert.rejects(resolvePageState({ browser: 'webkit' }, root, url, ctx), /webkit is not available/);
  } finally {
    setBlockPrivateUrls(false);
  }
  assert.equal((await resolvePageState({ browser: 'webkit' }, root, url, ctx)).browser, 'webkit');
});

test('device and channel: names are checked, a channel needs chromium', async () => {
  const root = realpathSync(mkdtempSync(path.join(os.tmpdir(), 'pw-device-')));
  const ctx = ctxFor(root);
  const url = 'http://example.test/';
  const mobile = await resolvePageState({ device: 'Pixel 7', channel: 'msedge' }, root, url, ctx);
  assert.equal(mobile.device, 'Pixel 7');
  assert.equal(mobile.channel, 'msedge');
  assert.match(describePageState(mobile, root), /Pixel 7/);
  assert.match(describePageState(mobile, root), /msedge/);
  await assert.rejects(resolvePageState({ device: 'x"; process.exit(1)' }, root, url, ctx), /not a Playwright device name/);
  await assert.rejects(resolvePageState({ browser: 'firefox', channel: 'chrome' }, root, url, ctx), /needs the chromium engine/);
});
